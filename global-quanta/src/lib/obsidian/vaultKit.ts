// L3 — Bộ khởi tạo Vault: một ghi chú "Bàn điều khiển Elite 10" (truy vấn Dataview) + 3 mẫu ghi chú cho plugin lõi Templates.
// Hàm thuần; thư mục lấy từ cấu hình người dùng (mặc định Global Quanta/Elite 10).
import { OBSIDIAN_DEFAULT_FOLDER, SOURCE_URL } from "./types";
import { safeFolder } from "./note";

export const VAULT_KIT_FILE = "Elite 10 · Bàn điều khiển.md";
const q = (s: string) => s.replace(/"/g, '\\"');

export function buildVaultKit(folderInput?: string | null): { fileName: string; folder: string; markdown: string } {
  const folder = safeFolder(folderInput) ?? OBSIDIAN_DEFAULT_FOLDER;
  const from = folder ? `FROM "${q(folder)}"` : "FROM \"\"";
  const dv = (body: string) => ["```dataview", body, "```"].join("\n");
  const md = [
    "---",
    "schema_version: 1",
    'type: "elite10-dashboard"',
    "tags:",
    '  - "global-quanta/elite10"',
    `source_url: "${SOURCE_URL}"`,
    "---",
    "",
    "# Elite 10 · Bàn điều khiển",
    "",
    "> Bảng tổng hợp mọi ghi chú xuất từ Phòng họp AI (tab QUYẾT ĐỊNH › 3. Phòng họp AI). Tham khảo định lượng — không phải khuyến nghị đầu tư.",
    "",
    "## Cài đặt một lần",
    "",
    "1. Bật plugin lõi **Templates** (Settings › Core plugins) và đặt thư mục mẫu, ví dụ `Templates`.",
    "2. Cài plugin cộng đồng **Dataview** (Settings › Community plugins › Browse › Dataview) để các bảng dưới đây hiện số liệu.",
    `3. Ghi chú xuất từ web nằm trong thư mục \`${folder || "(gốc Vault)"}\`. Chép 3 mẫu ở cuối trang vào thư mục mẫu.`,
    "4. (Tuỳ chọn) Cài plugin cộng đồng **Tasks** để các việc hậu kiểm 📅 hiện trong danh sách việc.",
    "",
    "## Ghi chú gần nhất",
    "",
    dv([`TABLE type AS "Loại", ticker AS "Mã", evidence_status AS "Bằng chứng", data_as_of AS "Dữ liệu tới"`, from, "WHERE schema_version = 1 AND type != \"elite10-dashboard\"", "SORT exported_at DESC", "LIMIT 30"].join("\n")),
    "",
    "## Theo mã",
    "",
    dv([`TABLE length(rows) AS "Số ghi chú", rows.file.link AS "Ghi chú"`, from, "WHERE ticker", "GROUP BY ticker AS \"Mã\"", "SORT length(rows) DESC"].join("\n")),
    "",
    "## Theo ngành ICB",
    "",
    dv([`TABLE length(rows) AS "Số ghi chú", rows.ticker AS "Mã"`, from, "WHERE sector_icb", "GROUP BY sector_icb AS \"Ngành ICB\""].join("\n")),
    "",
    "## Dở dang hoặc mô hình dự phòng",
    "",
    dv([`TABLE type AS "Loại", ticker AS "Mã", evidence_status AS "Trạng thái"`, from, "WHERE evidence_status AND evidence_status != \"complete\"", "SORT exported_at DESC"].join("\n")),
    "",
    "## Hậu kiểm đến hạn",
    "",
    dv([
      `TABLE ticker AS "Mã", review_5 AS "+5", outcome_5 AS "KQ +5", review_10 AS "+10", outcome_10 AS "KQ +10", review_20 AS "+20", outcome_20 AS "KQ +20"`,
      from,
      "WHERE type = \"elite10-decision-journal\" AND ((review_5 <= date(today) AND outcome_5 = null) OR (review_10 <= date(today) AND outcome_10 = null) OR (review_20 <= date(today) AND outcome_20 = null))",
      "SORT review_5 ASC",
    ].join("\n")),
    "",
    "## Trọng tài đúng hay sai (người dùng tự chấm)",
    "",
    dv([
      `TABLE length(rows) AS "Nhật ký", length(filter(rows, (r) => r.judge_was_right = true)) AS "Đúng", length(filter(rows, (r) => r.judge_was_right = false)) AS "Sai"`,
      from, "WHERE type = \"elite10-decision-journal\"", "GROUP BY dateformat(date, \"yyyy-MM\") AS \"Tháng\"", "SORT key DESC",
    ].join("\n")),
    "",
    "## Mẫu ghi chú (chép mỗi khối thành một tệp trong thư mục mẫu)",
    "",
    "### Mẫu: Mã cổ phiếu (`Mẫu - Mã.md`)",
    "",
    "~~~markdown",
    "---",
    'type: "gq-ticker"',
    "tags:",
    '  - "global-quanta/ticker"',
    "---",
    "# {{title}}",
    "",
    "## Mọi ghi chú nhắc tới mã này",
    "```dataview",
    "TABLE type AS \"Loại\", evidence_status AS \"Bằng chứng\", data_as_of AS \"Dữ liệu tới\"",
    "FROM [[]]",
    "SORT exported_at DESC",
    "```",
    "~~~",
    "",
    "### Mẫu: Ngành ICB (`Mẫu - Ngành.md`)",
    "",
    "~~~markdown",
    "---",
    'type: "gq-sector"',
    "tags:",
    '  - "global-quanta/sector"',
    "---",
    "# {{title}}",
    "",
    "## Ghi chú và mã liên quan",
    "```dataview",
    "TABLE ticker AS \"Mã\", type AS \"Loại\"",
    "FROM [[]]",
    "SORT exported_at DESC",
    "```",
    "~~~",
    "",
    "### Mẫu: Chủ đề vĩ mô (`Mẫu - Vĩ mô.md`)",
    "",
    "~~~markdown",
    "---",
    'type: "gq-macro"',
    "tags:",
    '  - "global-quanta/macro"',
    "---",
    "# {{title}}",
    "",
    "## Ghi chú nhắc tới chủ đề này",
    "```dataview",
    "LIST FROM [[]]",
    "SORT file.ctime DESC",
    "```",
    "~~~",
    "",
  ].join("\n");
  return { fileName: VAULT_KIT_FILE, folder, markdown: md };
}
